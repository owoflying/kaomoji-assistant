#: 强/弱信号的同情绪优先级：同位置命中时强信号优先
_SIGNAL_STRONG = 2
_SIGNAL_WEAK = 1

#: 允许在关键词中间跳过的**虚词**。
#:
#: 中文习惯在词里插字：「对胃口」→「对我胃口」、
#: 「累得不行」→「累得真的不行」。
#:
#: ⚠ 只收**结构虚词**，**不收程度副词和语气词**：
#: 实测收进"真""很"后，「这样真的好吗？」里的"真的"被当成"真的吗"→
#: 误判成惊讶。这类误报比多命中几个词条更伤。
_FILLER_CHARS = "的了得是我你他她"


def _iter_keywords():
    """产出 (emotion, keyword, signal_strength)。"""
    for emo, kws in EMOTION_KEYWORDS.items():
        for kw in kws:
            yield emo, kw, _SIGNAL_STRONG
    for emo, kws in WEAK_KEYWORDS.items():
        for kw in kws:
            yield emo, kw, _SIGNAL_WEAK


def _find_keyword(text, kw):
    """在 text 里找 kw，**允许中间插入少量虚词**。返回起始位置或 -1。

    ## 为什么需要它

    纯字面匹配对多字词条很脆弱——中文习惯在词中间插字：

        词表里的「对胃口」  实际常见写法是「对我胃口」
        词表里的「心里堵」  实际常见写法是「心里堵得慌」（这个能中）
        词表里的「累得不行」实际常见写法是「累得真的不行」

    实测「这配色真对我胃口」整句零命中，只因为中间多了个"我"。

    ## 做法

    按字逐个匹配，允许在两个相邻字之间跳过至多 1 个**虚词**
    （的/了/是/真/好/很/太/我/你/他/她/在/都/也/又/就）。

    限制跳过总数（≤2），避免"开心"跨半句话匹配到远处的"心"。
    """
    if not kw or not text:
        return -1
    # 先试直接匹配（最常见、最快）
    pos = text.rfind(kw)
    if pos >= 0:
        return pos
    if len(kw) < 2:
        return -1

    n = len(text)
    klen = len(kw)
    # 从右往左找起点，保证"最靠右优先"的语义
    for start in range(n - 1, -1, -1):
        if text[start] != kw[0]:
            continue
        i, j, skips = start, 1, 0
        while j < klen and i + 1 < n:
            i += 1
            if text[i] == kw[j]:
                j += 1
                continue
            # 允许跳过一个虚词
            if skips < 2 and text[i] in _FILLER_CHARS:
                skips += 1
                continue
            break
        if j >= klen:
            return start
    return -1


def detect_last(text: str):
    """返回文本中「最靠右」命中的情绪及其位置：(emotion, kw, pos)；未命中返回 None。

    规则（见模块文档）：
      1. 位置更靠右优先——用户最新输入的字在最右边；
      2. 同位置时强信号优先（"吗"不该盖过"开心"）；
      3. 再同则取更长的关键词；
      4. **弱信号单独命中时，必须句尾是问号才生效**，否则不触发
         （避免「吃饭了吗」「你在干什么」这类普通提问误弹）。

    ⚠ 第 4 条的关键实现细节：不能简单地"选中最靠右的那个再看它是不是弱信号"。
    反例「为什么会这样」——强信号"为什么"在位置 0，弱信号"什么"在位置 2，
    更靠右的弱信号会盖掉强信号；然后因为句尾没问号，整个判定被撤，
    **连本来命中的强信号一起丢了**。

    正确做法：**先按强弱分组，各自取最优**；弱信号组只有在"句尾问号"
    条件下才有资格参与最终比较。
    """
    if not text:
        return None

    # 句尾是否为疑问：决定弱信号能否参与
    tail = str(text).rstrip()
    question = bool(tail) and tail[-1] in "？?"

    def _best_of(want_strength):
        """在指定强度里找 (位置最靠右、词最长) 的那一个。"""
        best = None  # (pos, kw_len, emotion, kw)
        for emo, kw, strength in _iter_keywords():
            if strength != want_strength:
                continue
            pos = _find_keyword(text, kw)
            if pos < 0:
                continue
            # 位置优先，其次长度
            if best is None or (pos, len(kw)) > (best[0], best[1]):
                best = (pos, len(kw), emo, kw)
        return best

    strong = _best_of(_SIGNAL_STRONG)
    weak = _best_of(_SIGNAL_WEAK) if question else None

    # 强信号优先于弱信号：只要命中就返回（弱信号只是"可能"，不能盖过"确定"）
    if strong is not None:
        return strong[2], strong[3], strong[0]
    if weak is not None:
        return weak[2], weak[3], weak[0]
    return None
