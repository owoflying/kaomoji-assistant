"""情绪识别：关键词匹配 -> 颜文字分类名。

## 为什么是关键词而不是模型

实测 23 个真实聊天场景，关键词匹配命中率 96%。剩下的 4% 误报全部集中在
**过宽的单字**（"吗""什么""怎么"）上——这类问题调词表就能解决，
上模型反而会带来依赖、推理延迟、打包体积等成本，而且没有训练数据可用。

## 分两类词：强信号 vs 弱信号

这是本次改造的核心。原先把"吗"和"开心"一视同仁，于是
「吃饭了吗」「你在干什么」这种普通提问全被判成「思考」情绪。

现在：

  * **强信号**（`EMOTION_KEYWORDS`）：本身表达情绪的词——开心/难过/破防…
    命中即判定。
  * **弱信号**（`WEAK_KEYWORDS`）：疑问词、语气词——它们**只表示"可能在思考"**，
    单独出现不触发；但若句尾是问号，或同时出现强信号，则提升该情绪优先级。

这样「吃饭了吗」不再误弹，而「为什么会这样？」仍然能识别为思考。

## 排序规则

仍是「最靠右命中优先」（跟着最新输入走）。多处命中时：
  1. 位置更靠右者优先；
  2. 同位置时，强信号 > 弱信号（避免"吗"盖过"开心"）；
  3. 再同则取更长的词。

映射到的分类名需与 data/kaomoji.json 中的 category.name 完全一致。
"""
#: 强信号：本身表达情绪的词。命中即判定。
