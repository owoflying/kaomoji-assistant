#: 弱信号：疑问词 / 语气词。**单独出现不触发**情绪，
#: 只在"句尾有问号"或"同时有强信号"时作为辅助。
WEAK_KEYWORDS = {
    "思考": ["？", "?", "吗", "什么", "怎么", "如何", "咋", "是不是", "难道"],
}

#: 强/弱信号的同情绪优先级：同位置命中时强信号优先
_SIGNAL_STRONG = 2
_SIGNAL_WEAK = 1


def _iter_keywords():
    """产出 (emotion, keyword, signal_strength)。"""
    for emo, kws in EMOTION_KEYWORDS.items():
        for kw in kws:
            yield emo, kw, _SIGNAL_STRONG
    for emo, kws in WEAK_KEYWORDS.items():
        for kw in kws:
            yield emo, kw, _SIGNAL_WEAK


def detect_last(text: str):
    """返回文本中「最靠右」命中的情绪及其位置：(emotion, kw, pos)；未命中返回 None。

    规则（见模块文档）：
      1. 位置更靠右优先——用户最新输入的字在最右边；
      2. 同位置时强信号优先（"吗"不该盖过"开心"）；
      3. 再同则取更长的关键词；
      4. **弱信号单独命中时，必须句尾是问号才生效**，否则不触发
         （避免「吃饭了吗」「你在干什么」这类普通提问误弹）。

    ⚠ 第 4 条的关键实现细节：不能简单地"选中最靠右的那个再看它是不是弱信号"。
    反例「为什么会这样」——强信号"为什么"在位置 0，弱信号"什么"在位置 2，
    更靠右的弱信号会盖掉强信号；然后因为句尾没问号，整个判定被撤，
    **连本来命中的强信号一起丢了**。

    正确做法：**先按强弱分组，各自取最优**；弱信号组只有在"句尾问号"
    条件下才有资格参与最终比较。
    """
    if not text:
        return None

    # 句尾是否为疑问：决定弱信号能否参与
    tail = str(text).rstrip()
    question = bool(tail) and tail[-1] in "？?"

    def _best_of(want_strength):
        """在指定强度里找 (位置最靠右、词最长) 的那一个。"""
        best = None  # (pos, kw_len, emotion, kw)
        for emo, kw, strength in _iter_keywords():
            if strength != want_strength:
                continue
            pos = text.rfind(kw)
            if pos < 0:
                continue
            # 位置优先，其次长度
            if best is None or (pos, len(kw)) > (best[0], best[1]):
                best = (pos, len(kw), emo, kw)
        return best

    strong = _best_of(_SIGNAL_STRONG)
    weak = _best_of(_SIGNAL_WEAK) if question else None

    # 强信号优先于弱信号：只要命中就返回（弱信号只是"可能"，不能盖过"确定"）
    if strong is not None:
        return strong[2], strong[3], strong[0]
    if weak is not None:
        return weak[2], weak[3], weak[0]
    return None
